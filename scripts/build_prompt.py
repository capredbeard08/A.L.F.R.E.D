#!/usr/bin/env python3
"""Deterministically assemble the A.L.F.R.E.D. system prompt.

Reads the modular sources under prompts/ in a fixed order and emits a single
ALFRED.system.md. Output is byte-for-byte reproducible: no timestamps, no
absolute paths, no locale-dependent formatting.

Usage:
    python3 scripts/build_prompt.py            # write ALFRED.system.md
    python3 scripts/build_prompt.py --check    # verify committed file is in sync
    python3 scripts/build_prompt.py --stdout   # print to stdout, write nothing
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PROMPTS_DIR = REPO_ROOT / "prompts"
OUTPUT_PATH = REPO_ROOT / "ALFRED.system.md"

# Fixed assembly order. Top-level modules first, then the five domains in
# canonical order, then the execution/tone modules. Editing this list changes
# the prompt, which is intentional: the order is part of the contract.
MODULES: tuple[str, ...] = (
    "persona.md",
    "domains/financial_capital_allocation.md",
    "domains/business_corporate_strategy.md",
    "domains/data_systems_engineering.md",
    "domains/hardware_fabrication.md",
    "domains/governance_intelligence.md",
    "domains/tools_and_research.md",
    "domains/07_roles.md",
    "bluf_protocol.md",
    "code_tool_execution.md",
    "tone.md",
)

# Substrings that must appear in the assembled prompt for it to be considered
# complete. Guards against a module being emptied or a heading being renamed.
REQUIRED_MARKERS: tuple[str, ...] = (
    "A.L.F.R.E.D.",
    "FINANCIAL & CAPITAL ALLOCATION",
    "BUSINESS & CORPORATE STRATEGY",
    "DATA & SYSTEMS ENGINEERING",
    "HARDWARE & FABRICATION",
    "GOVERNANCE & INTELLIGENCE",
    "TOOLS & RESEARCH",
    "PROFESSIONAL ROLE TAXONOMY",
    "EXECUTIVE COMMUNICATION PROTOCOL",
    "CODE & TOOL EXECUTION RULES",
    "DEFAULT TONE & CHARACTER",
)

HEADER = """<!-- Generated by scripts/build_prompt.py. Do not edit by hand. -->
<!-- Edit the modules under prompts/ instead, then re-run the build. -->
"""


class BuildError(Exception):
    """Raised when a module is missing, empty, or the result is incomplete."""


def read_module(relative_path: str) -> str:
    """Read one module and normalise it. Raises BuildError on any problem."""
    path = PROMPTS_DIR / relative_path
    if not path.is_file():
        raise BuildError(f"missing module: prompts/{relative_path}")
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError as exc:
        raise BuildError(f"module is not valid UTF-8: prompts/{relative_path}") from exc
    text = text.replace("\r\n", "\n").replace("\r", "\n").strip()
    if not text:
        raise BuildError(f"module is empty: prompts/{relative_path}")
    return text


def assemble() -> str:
    """Concatenate all modules in order into the final system prompt."""
    parts = [HEADER.strip()]
    for relative_path in MODULES:
        parts.append(read_module(relative_path))
    prompt = "\n\n---\n\n".join(parts) + "\n"

    missing = [m for m in REQUIRED_MARKERS if m not in prompt]
    if missing:
        raise BuildError("assembled prompt is missing required sections: " + ", ".join(missing))
    return prompt


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build ALFRED.system.md from prompts/.")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="fail if output is stale")
    group.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = parser.parse_args(argv)

    try:
        prompt = assemble()
    except BuildError as exc:
        print(f"build failed: {exc}", file=sys.stderr)
        return 1

    if args.stdout:
        sys.stdout.write(prompt)
        return 0

    if args.check:
        if not OUTPUT_PATH.is_file():
            print(f"check failed: {OUTPUT_PATH.name} does not exist", file=sys.stderr)
            return 1
        current = OUTPUT_PATH.read_text(encoding="utf-8")
        if current != prompt:
            print(
                f"check failed: {OUTPUT_PATH.name} is out of date; re-run scripts/build_prompt.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {OUTPUT_PATH.name} is in sync ({len(prompt)} bytes)")
        return 0

    OUTPUT_PATH.write_text(prompt, encoding="utf-8")
    print(f"wrote {OUTPUT_PATH.name} ({len(prompt)} bytes, {len(MODULES)} modules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
